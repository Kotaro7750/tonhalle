for (const dragTarget of ['handle', 'row'] as const) {
  test(`dragging from the ${dragTarget} lifts the whole row and previews sorting before release`, async ({ page }, testInfo) => {
    await mockLibrary(page)
    await page.goto(`/#/releases/${releaseId}`)
    await page.getByRole('button', { name: 'Add to queue: First Light' }).click()
    await page.getByRole('button', { name: 'Add to queue: Second Light' }).click()
    await page.getByRole('button', { name: 'Open queue', exact: true }).click()
    const queue = page.getByRole('dialog', { name: 'Queue', exact: true })
    await expect.poll(async () => (await queue.boundingBox())?.y).toBeLessThan(100)
    await expect.poll(() => queue.evaluate((el) => el.getAnimations().every((animation) => animation.playState !== 'running'))).toBe(true)
    const rows = queue.locator('[data-queue-state="upcoming"]')
    const firstBounds = (await rows.first().boundingBox())!
    const target = dragTarget === 'handle' ? queue.getByRole('button', { name: 'Reorder Second Light' }) : rows.last().getByText('Second Light', { exact: true })
    const bounds = (await target.boundingBox())!
    const x = bounds.x + bounds.width / 2
    const y = bounds.y + bounds.height / 2
    const targetY = firstBounds.y + firstBounds.height / 2
    const session = testInfo.project.name === 'mobile' ? await page.context().newCDPSession(page) : null
    if (session) {
      await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
      await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - 10 }] })
      await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: targetY }] })
    } else {
      await page.mouse.move(x, y)
      await page.mouse.down()
      await page.mouse.move(x, y - 10)
      await page.mouse.move(x, targetY, { steps: 8 })
    }
    const overlay = page.locator('[data-queue-drag-overlay]')
    await expect(overlay).toBeVisible()
    await expect(overlay).toContainText('Second Light')
    expect((await overlay.boundingBox())!.width).toBeGreaterThan(firstBounds.width - 2)
    await page.screenshot({ path: testInfo.outputPath('queue-drag.png') })
    await expect.poll(async () => (await rows.first().boundingBox())!.y).toBeGreaterThan(firstBounds.y + firstBounds.height / 2)
    if (session) {
      await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
      await session.detach()
    } else await page.mouse.up()
    await expect(rows.first()).toContainText('Second Light')
    await expect(overlay).toHaveCount(0)
    await expect(page.locator('audio')).toHaveCount(0)
  })
}

