test('queue additions stay idle, reject duplicates and play in order until the end', async ({ page }, testInfo) => {
  await mockLibrary(page)
  await page.goto(`/#/releases/${releaseId}`)
  await page.getByRole('button', { name: 'Add to queue: First Light', exact: true }).click()
  await page.getByRole('button', { name: 'Add to queue: Second Light', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Queued: First Light' })).toBeDisabled()
  await expect(page.locator('audio')).toHaveCount(0)
  await page.getByRole('button', { name: 'Open queue', exact: true }).click()
  const queue = page.getByRole('dialog', { name: 'Queue', exact: true })
  await expect(queue.locator('[data-queue-state="upcoming"]')).toHaveCount(2)
  await expect.poll(async () => (await queue.boundingBox())?.y).toBeLessThan(100)
  await page.screenshot({ path: testInfo.outputPath('queue.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await queue.getByRole('button', { name: 'Play First Light' }).click()
  const audio = page.locator('audio')
  await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => el.paused)).toBe(false)
  await expect(queue.locator('[data-queue-state="upcoming"]')).toHaveCount(1)
  await expect(queue.getByRole('list', { name: 'Queued tracks' }).getByRole('listitem')).toHaveCount(2)
  await expect(queue.locator('[aria-current="true"]')).toContainText('First Light')
  const currentBackground = await queue.locator('[data-queue-state="current"] > div').evaluate((el) => getComputedStyle(el).backgroundColor)
  const upcomingBackground = await queue.locator('[data-queue-state="upcoming"] > div').evaluate((el) => getComputedStyle(el).backgroundColor)
  expect(currentBackground).not.toBe(upcomingBackground)
  await audio.evaluate((el: HTMLAudioElement) => { el.currentTime = 14.8 })
  await expect(queue.getByText('Second Light', { exact: true })).toBeVisible()
  await expect(queue.locator('[data-queue-state="upcoming"]')).toHaveCount(0)
  await expect(queue.locator('[data-queue-state="played"]')).toHaveCount(1)
  await expect(queue.locator('[aria-current="true"]')).toContainText('Second Light')
  const playedBackground = await queue.locator('[data-queue-state="played"] > div').evaluate((el) => getComputedStyle(el).backgroundColor)
  expect(playedBackground).not.toBe(currentBackground)
  expect(playedBackground).not.toBe(upcomingBackground)
  await page.screenshot({ path: testInfo.outputPath('queue-states.png') })
  await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => el.paused)).toBe(false)
  await audio.evaluate((el: HTMLAudioElement) => { el.currentTime = 14.8 })
  await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => el.ended)).toBe(true)
  await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => el.paused)).toBe(true)
  await queue.getByRole('button', { name: 'Collapse queue' }).press('ArrowDown')
  await expect(queue).toHaveCount(0)
})

