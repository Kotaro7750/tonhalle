test('played and current tracks can be reordered without interrupting audio', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await mockLibrary(page)
  await page.goto(`/#/releases/${releaseId}`)
  await page.getByRole('button', { name: 'Play First Light', exact: true }).click()
  await page.getByRole('button', { name: 'Add to queue: Second Light' }).click()
  const mini = page.getByRole('complementary', { name: 'Now playing' })
  await mini.getByRole('button', { name: 'Next track' }).click()
  await mini.getByRole('button', { name: 'Pause', exact: true }).click()
  const audio = await page.locator('audio').elementHandle()
  await audio!.evaluate((el: HTMLAudioElement) => { el.currentTime = 3 })
  await mini.getByRole('button', { name: 'Open queue' }).click()
  const queue = page.getByRole('dialog', { name: 'Queue', exact: true })
  const rows = queue.getByRole('listitem')
  const reorder = async (title: string, direction: 'ArrowDown' | 'ArrowUp') => {
    await expect.poll(() => rows.evaluateAll((elements) => elements.every((el) => el.getAnimations().every((animation) => animation.playState !== 'running')))).toBe(true)
    const handle = queue.getByRole('button', { name: `Reorder ${title}` })
    await handle.focus()
    await handle.press('Space')
    const overlay = page.locator('[data-queue-drag-overlay]')
    await expect(overlay).toBeVisible()
    const y = (await overlay.boundingBox())!.y
    await handle.press(direction)
    if (direction === 'ArrowDown') await expect.poll(async () => (await overlay.boundingBox())!.y).toBeGreaterThan(y + 20)
    else await expect.poll(async () => (await overlay.boundingBox())!.y).toBeLessThan(y - 20)
    await handle.press('Space')
    await expect(overlay).toHaveCount(0)
  }
  await reorder('First Light', 'ArrowDown')
  await expect(rows.first()).toContainText('Second Light')
  await expect(queue.locator('[data-queue-state="upcoming"]')).toContainText('First Light')
  await reorder('Second Light', 'ArrowDown')
  await expect(rows.first()).toContainText('First Light')
  await expect(queue.locator('[data-queue-state="played"]')).toContainText('First Light')
  await reorder('Second Light', 'ArrowUp')
  await expect(rows.first()).toContainText('Second Light')
  expect(await audio!.evaluate((el: HTMLAudioElement) => ({ connected: el.isConnected, paused: el.paused, time: el.currentTime }))).toEqual({ connected: true, paused: true, time: 3 })
  await queue.getByRole('button', { name: 'Close queue' }).click()
  await mini.getByRole('button', { name: 'Next track' }).click()
  await expect(mini.getByRole('link', { name: 'Open player: First Light' })).toBeVisible()
})

