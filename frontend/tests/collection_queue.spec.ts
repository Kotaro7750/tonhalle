test('a failed bulk load preserves current playback', async ({ page }) => {
  await mockLibrary(page)
  await page.route(`**/api/v0/tracks/${secondTrackId}`, (route) => route.fulfill({ status: 404, json: { title: 'Track unavailable' } }))
  await page.goto(`/#/releases/${releaseId}`)
  await page.getByRole('button', { name: 'Play First Light', exact: true }).click()
  const audio = await page.locator('audio').elementHandle()
  await expect.poll(() => audio!.evaluate((el: HTMLAudioElement) => el.paused)).toBe(false)
  await page.getByRole('button', { name: `Play release: ${releaseTitle}` }).click()
  await expect(page.getByRole('alert')).toContainText('Track unavailable')
  expect(await audio!.evaluate((el: HTMLAudioElement) => el.isConnected && !el.paused)).toBe(true)
  await expect(page.getByRole('complementary', { name: 'Now playing' }).getByLabel('1 track in queue')).toBeVisible()
})

test('collection checks cover current and queued tracks and update after removal in details and library', async ({ page }) => {
  await mockLibrary(page)
  await page.goto(`/#/releases/${releaseId}`)
  await page.getByRole('button', { name: 'Play First Light', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Queued disc 1', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: `Add release: ${releaseTitle} to queue`, exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Add disc 2 to queue', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Queued disc 2', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: `Queued release: ${releaseTitle}`, exact: true })).toBeDisabled()
  await page.getByRole('link', { name: 'Releases', exact: true }).click()
  await expect(page.getByRole('button', { name: `Queued release: ${releaseTitle}`, exact: true })).toBeDisabled()
  await page.getByRole('complementary', { name: 'Now playing' }).getByRole('button', { name: 'Open queue' }).click()
  const queue = page.getByRole('dialog', { name: 'Queue', exact: true })
  await queue.getByRole('button', { name: 'Remove from queue: Second Light' }).click()
  await queue.getByRole('button', { name: 'Close queue' }).click()
  await expect(page.getByRole('button', { name: `Add release: ${releaseTitle} to queue`, exact: true })).toBeEnabled()
  await page.getByRole('button', { name: `Add release: ${releaseTitle} to queue`, exact: true }).click()
  await expect(page.getByRole('button', { name: `Queued release: ${releaseTitle}`, exact: true })).toBeDisabled()
})
