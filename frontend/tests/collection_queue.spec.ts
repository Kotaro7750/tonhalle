import { test, expect } from '@playwright/test'
import { mockLibrary, releaseId, secondTrackId } from './fixtures'

const releaseTitle = 'Evening Sessions'

test('idle queue centers queue actions and hides playback information', async ({ page }, testInfo) => {
  await mockLibrary(page)
  await page.goto(`/#/releases/${releaseId}`)
  await expect(page.getByRole('banner').getByRole('button', { name: 'Open queue' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Add to queue: First Light' }).click()
  const mini = page.getByRole('complementary', { name: 'Now playing' })
  await expect(mini).toBeVisible()
  await expect(mini.getByText('No track selected')).toHaveCount(0)
  for (const name of ['Play', 'Restart track', 'Back 15 seconds', 'Forward 15 seconds', 'Repeat mode']) {
    await expect(mini.getByRole('button', { name, exact: true })).toHaveCount(0)
  }
  await expect(mini.getByRole('button', { name: 'Clear queue', exact: true })).toBeEnabled()
  await expect(mini.getByRole('button', { name: 'Play queue from start', exact: true })).toBeEnabled()
  await expect(page.locator('audio')).toHaveCount(0)
  await expect(mini.getByLabel('1 track in queue')).toHaveText('1')
  await page.getByRole('button', { name: 'Add to queue: Second Light' }).click()
  await expect(mini.getByLabel('2 tracks in queue')).toHaveText('2')
  await page.screenshot({ path: testInfo.outputPath('idle-mini-queue.png') })
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveClass('dark')
  await page.screenshot({ path: testInfo.outputPath('idle-mini-queue-dark.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await mini.getByRole('button', { name: 'Play queue from start', exact: true }).click()
  await expect(mini.getByLabel('2 tracks in queue')).toHaveText('2')
  await expect(mini.getByRole('button', { name: 'Pause', exact: true })).toBeVisible()
})

test('disc and release actions add without duplicates and replace the queue when playing', async ({ page }) => {
  await mockLibrary(page)
  await page.goto(`/#/releases/${releaseId}`)
  await page.getByRole('button', { name: 'Add disc 2 to queue', exact: true }).click()
  const mini = page.getByRole('complementary', { name: 'Now playing' })
  await expect(mini.getByLabel('1 track in queue')).toBeVisible()
  await page.getByRole('button', { name: 'Add disc 1 to queue', exact: true }).click()
  await expect(mini.getByLabel('2 tracks in queue')).toBeVisible()
  await expect(page.getByRole('button', { name: `Queued release: ${releaseTitle}`, exact: true })).toBeDisabled()
  await expect(mini.getByLabel('2 tracks in queue')).toBeVisible()
  await page.getByRole('button', { name: `Play release: ${releaseTitle}`, exact: true }).click()
  await expect(mini.getByRole('link', { name: 'Open player: First Light' })).toBeVisible()
  await expect(mini.getByRole('button', { name: 'Pause', exact: true })).toBeVisible()
  await mini.getByRole('button', { name: 'Open queue' }).click()
  const queue = page.getByRole('dialog', { name: 'Queue', exact: true })
  await expect(queue.locator('[data-queue-state="upcoming"]')).toHaveCount(1)
  await expect(queue.locator('[data-queue-state="upcoming"]')).toContainText('Second Light')
  await queue.getByRole('button', { name: 'Close queue' }).click()
  await page.getByRole('button', { name: 'Play disc 2', exact: true }).click()
  await expect(mini.getByRole('link', { name: 'Open player: Second Light' })).toBeVisible()
  await expect(mini.getByLabel('1 track in queue')).toBeVisible()
  const audio = await page.locator('audio').elementHandle()
  await expect.poll(() => audio!.evaluate((el: HTMLAudioElement) => el.paused)).toBe(false)
  await page.getByRole('button', { name: 'Add disc 1 to queue', exact: true }).click()
  expect(await audio!.evaluate((el: HTMLAudioElement) => el.isConnected && !el.paused)).toBe(true)
  await expect(mini.getByLabel('2 tracks in queue')).toBeVisible()
})

